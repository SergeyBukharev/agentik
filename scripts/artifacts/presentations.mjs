await mkdir(output, {recursive:true});
for (const [name, content] of [['agentik-prd', prd], ['agentik-product-story', story]]) {
  const presentation = await PresentationFile.importPptx(await FileBlob.load(join(repo, 'docs', `${name}.pptx`)));
  if (presentation.slides.items.length !== content.length) throw new Error(`Unexpected slide count in ${name}`);

  for (const [index, slide] of presentation.slides.items.entries()) {
    const {copy, notes} = content[index];
    for (const [label, value] of Object.entries(copy)) {
      const shape = slide.shapes.items.find(item => item.name === label);
      if (!shape) throw new Error(`Missing shape ${label} in ${name} slide ${index + 1}`);
      const previous = shape.text.toString();
      if (previous !== value) shape.text.replace(previous, value);
      if (shape.text.toString() !== value) throw new Error(`Text replacement failed for ${label} in ${name} slide ${index + 1}`);
    }
    slide.speakerNotes.text = notes;
  }

  const draft = join(output, `${name}.pptx`);
  await (await PresentationFile.exportPptx(presentation)).save(draft);
  const exported = await PresentationFile.importPptx(await FileBlob.load(draft));
  const renderDir = join(output, name);
  await mkdir(renderDir, {recursive:true});
  for (const [index, slide] of exported.slides.items.entries()) {
    const image = await exported.export({slide, format:'png', scale:1});
    await writeFile(join(renderDir, `slide-${index + 1}.png`), new Uint8Array(await image.arrayBuffer()));
  }
  console.log(`${draft} (${exported.slides.items.length} slides exported and rendered)`);
}
