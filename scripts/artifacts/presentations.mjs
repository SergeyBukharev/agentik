function cards(...columns) {
  return Object.fromEntries(columns.flatMap(([heading, body], index) => [
    [`card heading ${index + 1}`, heading], [`card body ${index + 1}`, body],
  ]));
}

function rows(...items) {
  return Object.fromEntries(items.flatMap(([heading, body, criterion], index) => [
    [`item ${index}`, heading], [`explanation ${index}`, body],
    ...(criterion ? [[`criterion ${index}`, criterion]] : []),
  ]));
}

